"""Retain actual CLI results for the producer capture and labelled boundary fixtures."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--executable", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--artifacts", type=Path, required=True)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    args.artifacts.mkdir(parents=True, exist_ok=True)
    command = (
        [str(args.executable)] if args.executable else [sys.executable, "-m", "trainspotter.cli"]
    )
    finite = [5.0] * 20 + [1.0] * 40 + [4.0] * 20 + [1.0] * 40
    examples = {
        "finite-control": finite,
        "gap-recovery": [5.0] * 20 + [1.0] * 40 + [math.nan] * 10 + [4.0] * 20
                        + [math.nan] * 10 + [1.0] * 40,
        "gap-level-change": [1.0] * 50 + [math.nan] * 10 + [3.0] * 50,
        "nonfinite-tail": [5.0] * 20 + [1.0] * 40 + [4.0] * 20 + [math.nan] * 20,
        "gap-spike": [5.0] * 20 + [1.0] * 40 + [math.nan] * 10 + [4.0] + [1.0] * 40,
        "after-gap-control": [1.0] * 30 + [math.nan] * 10 + finite,
        "all-nonfinite": [math.nan] * 10,
        "short-segments": [1.0] * 5 + [math.nan] + [5.0] * 5,
        "final-rise": [1.0] * 40 + [math.nan] * 10 + [3.0 + i * 0.07 for i in range(50)],
    }
    paths = {"producer": ROOT / "captured/observed.csv"}
    for name, values in examples.items():
        path = args.artifacts / f"{name}.csv"
        with path.open("w", newline="") as handle:
            writer = csv.writer(handle, lineterminator="\n")
            writer.writerow(["step", "loss"])
            writer.writerows(enumerate(values))
        paths[name] = path
    manifest = json.loads((ROOT / "captured/capture.json").read_text())
    for name, expected_hash in manifest["files"].items():
        assert hashlib.sha256((ROOT / "captured" / name).read_bytes()).hexdigest() == expected_hash
    # Independently check the training experiment's known closed form and restore event.
    with (ROOT / "captured/objective.csv").open() as handle:
        truth = list(csv.DictReader(handle))
    for row in truth:
        step = int(row["step"])
        elapsed = step if step < 70 else step - 70 if step < 95 else 59 + step - 95
        weight = 3 * 0.95**elapsed
        assert math.isclose(float(row["weight"]), weight, rel_tol=1e-13)
        assert math.isclose(float(row["objective"]), 1 + weight**2 / 2, rel_tol=1e-13)
    results = {}
    for name, path in paths.items():
        process = subprocess.run(
            [*command, "analyze", str(path.resolve()), "--output", "json", "--fail-on", "error"],
            capture_output=True, text=True, check=False,
        )
        assert not process.stderr, (name, process.stderr)
        report = json.loads(process.stdout)
        findings = report["findings"]
        trajectory = [f for f in findings if f["detector"] in ("spikes", "setbacks")
                      or (f["detector"] == "divergence" and "non-finite" not in f["title"].lower())]
        if args.verify:
            assert process.returncode == (0 if name == "finite-control" else 1), name
            if name in ("producer", "gap-recovery", "gap-level-change", "nonfinite-tail",
                        "gap-spike", "all-nonfinite", "short-segments"):
                assert not trajectory, (name, trajectory)
            if name in ("finite-control", "after-gap-control"):
                assert any(f["detector"] == "setbacks" for f in trajectory), name
            if name == "final-rise":
                assert trajectory and all(f["step_start"] >= 50 for f in trajectory)
        results[name] = {
            "provenance": "captured PyTorch with deliberate logging fault" if name == "producer"
                          else "synthetic boundary/control fixture generated by replay.py",
            "input_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "exit_code": process.returncode, "input_complete": report["run"]["input_complete"],
            "findings": findings,
        }
    args.out.write_text(json.dumps({"producer_closed_form_checked": True,
                                    "cases": results}, indent=2) + "\n")
    print(json.dumps({name: [f["title"] for f in record["findings"]]
                      for name, record in results.items()}, indent=2))


if __name__ == "__main__":
    main()
